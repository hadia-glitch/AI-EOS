# ── Rule-based fallback ───────────────────────────────────────────────────────

def _fallback_explanation(
    risk_payload: dict[str, Any],
    active_guideline: str,
    chunks: list[EvidenceChunkResult],
) -> ExplanationResponse:
    """Deterministic rule-based summary. Explicitly NOT AI-generated."""
    category = str(risk_payload.get("category", risk_payload.get("risk_category", "INTERMEDIATE")))
    score = risk_payload.get("total_score", risk_payload.get("combined_score", 0))

    actions_map = {
        "LOW": [
            "Routine observation per unit protocol.",
            "Monitor vital signs every 12 hours for the first 24 hours.",
            "Reassess if any clinical signs develop.",
        ],
        "INTERMEDIATE": [
            "Enhanced monitoring every 4 hours.",
            "Obtain blood culture and CRP at 18–24 hours.",
            "Senior clinician review if clinical status deteriorates.",
            "Review antibiotic decision at 36 hours based on culture and CRP.",
        ],
        "HIGH": [
            "Obtain blood culture before antibiotics — do not delay treatment.",
            "Initiate empirical IV antibiotics within 1 hour per active guideline.",
            "Senior neonatologist review within 1 hour.",
            "Repeat CRP at 18–24 hours; review blood culture at 36–48 hours.",
        ],
        "CRITICAL": [
            "Immediate IV antibiotics — do not wait for culture results.",
            "NICU admission and full sepsis workup.",
            "Supportive care: perfusion, ventilation, thermal management.",
            "Senior neonatologist within 30 minutes.",
            "Urgent FBC, CRP, blood gas, and blood culture.",
        ],
    }

    category_key = category.upper().replace(" ", "_")
    actions = actions_map.get("INTERMEDIATE", [])
    for key, value in actions_map.items():
        if key in category_key:
            actions = value
            break

    citations = [
        CitationItem(source=c.source_name, section=c.section,
                     chunk_id=c.chunk_id, similarity_score=c.similarity_score,
                     page_number=c.page_number, file_name=c.file_name)
        for c in chunks
    ]
    drivers_text = ", ".join(
        d.get("name", "") for d in risk_payload.get("drivers", []) if isinstance(d, dict)
    ) or "none identified"

    return ExplanationResponse(
        clinical_summary=(
            f"Rule-based summary (no AI): This infant has {category} EOS risk "
            f"(score {score}) based on the EOSCAL three-layer assessment. "
            f"Active risk drivers: {drivers_text}. "
            f"Recommendations follow {active_guideline} protocol."
        ),
        per_driver_explanations=[
            {"factor": d.get("name", "Unknown"), "explanation": d.get("reason", "Contributed to risk score.")}
            for d in risk_payload.get("drivers", [])[:6]
            if isinstance(d, dict)
        ],
        recommended_actions=actions,
        evidence_summary=chunks[0].chunk_text[:200] + "…" if chunks else "No guideline chunks retrieved.",
        citation_list=citations,
        confidence_disclaimer=RULE_BASED_DISCLAIMER,
        rag_chunks=[EvidenceChunkResponse(**c.to_dict()) for c in chunks],
        model_version="rule-based-fallback",
        fallback_used=True,
        evidence_labels=_build_evidence_label_refs(chunks, label_evidence_chunks(chunks)[1]),
    )


def _maybe_fact_check_explanation(
    result: ExplanationResponse,
    risk_payload: dict[str, Any],
    active_guideline: str,
    chunks: list[EvidenceChunkResult],
) -> FactCheckResult:
    """Runs the judge only for HIGH/CRITICAL categories (see config.fact_check_categories)."""
    category = risk_payload.get("category", risk_payload.get("risk_category", ""))
    if not should_fact_check(category):
        return FactCheckResult(performed=False)
    draft = summarize_explanation_for_judge(
        result.clinical_summary, result.per_driver_explanations,
        result.recommended_actions, result.evidence_summary,
    )
    return run_fact_check(draft, risk_payload, active_guideline, chunks)


# ── Main entry point ──────────────────────────────────────────────────────────

def generate_explanation(
    risk_payload: dict[str, Any],
    active_guideline: str,
    chunks: list[EvidenceChunkResult],
    query: str = "",
) -> ExplanationResponse:
    settings = get_settings()
    chunk_responses = [EvidenceChunkResponse(**c.to_dict()) for c in chunks]
    cache_key = _make_cache_key(risk_payload, active_guideline)

    # ── 1. Cache ──────────────────────────────────────────────────────────────
    # A rule-based-fallback cache hit is deliberately NOT returned here — it
    # falls through to a live LLM attempt below instead, so a plan that was
    # cached while every provider was down gets transparently upgraded to a
    # real AI explanation the next time an LLM is reachable, without the
    # clinician needing to do anything. Only a genuine AI-generated hit
    # short-circuits and returns immediately (no wasted LLM call/latency for
    # an answer that hasn't changed). If the live attempt below also fails,
    # the existing rule-based-fallback path regenerates and rewrites the
    # same cache_key, so this never leaves the clinician without an answer.
    cached = _check_cache(cache_key)
    if cached is not None and not cached.fallback_used:
        cached.rag_chunks = chunk_responses
        _log_rag_query(query or "cached", active_guideline, chunks, method="cache")
        return cached
    if cached is not None and cached.fallback_used:
        print(f"[LLM] Cached explanation was rule-based-fallback — attempting live upgrade (key={cache_key})")

    # ── 2. Log RAG query ──────────────────────────────────────────────────────
    _log_rag_query(
        query or _build_query_string(risk_payload, active_guideline),
        active_guideline, chunks,
        method="hybrid" if chunks else "seed",
    )

    prompt, label_map = _build_prompt(risk_payload, active_guideline, chunks)

    # ── 3. Try the LLM provider chain (Local -> Gemini -> Groq) ──────────────
    try:
        raw, model_used = call_llm(prompt, settings)
        result = _parse_llm_response(raw, chunks, model_used, chunk_responses, label_map=label_map)
        result.fact_check = _maybe_fact_check_explanation(result, risk_payload, active_guideline, chunks)
        _write_cache(cache_key, risk_payload, active_guideline, result,
                     chunks, model_used, is_simulated=False)
        print(f"[LLM] Explanation generated via {model_used}")
        return result
    except LLMUnavailableError as e:
        print(f"[LLM] All providers unavailable ({e}) — using rule-based fallback")

    # ── 5. Rule-based final fallback ──────────────────────────────────────────
    print("[LLM] Both Gemini and Groq unavailable — using rule-based fallback")
